"""Contract tests for the generated-test validator (framework/sps2/tools/check_generated_tests.py).

T-20: gen_law_test.py emits negative regression tests (test_law_regress_*.py)
that are NOT valid until a human fills the reviewed-by header. These tests pin
that the validator:
1. passes a well-formed generated test (auto-marker + reviewed-by filled),
2. FIRES on a missing reviewed-by header,
3. FIRES on an empty or placeholder reviewed-by value, and
4. ignores non-generated test files entirely.

Runs the validator as a subprocess against a temp tests dir — same
invocation style as test_law_checker.py, but scoped to a scratch directory
so the live tree is never touched.
"""
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
TOOL = REPO_ROOT / "framework" / "sps2" / "tools" / "check_generated_tests.py"

AUTO_LINE = "# AUTO-GENERATED by gen_law_test.py (T-20)"
REVIEWED_LINE = "# reviewed by: Maryam, 2026-10-18"


def _write_generated_test(tests_dir: Path, name: str, reviewed_line: str | None) -> Path:
    tests_dir.mkdir(parents=True, exist_ok=True)
    lines = ["# Negative regression test for a law check.", AUTO_LINE]
    if reviewed_line is not None:
        lines.append(reviewed_line)
    lines += [
        "import unittest",
        "",
        "",
        "class TestRegress(unittest.TestCase):",
        "    def test_rule_holds(self) -> None:",
        "        self.assertTrue(True)",
        "",
        "",
        'if __name__ == "__main__":',
        "    unittest.main()",
    ]
    path = tests_dir / name
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _run_validator(tests_dir: Path):
    proc = subprocess.run(
        [sys.executable, str(TOOL), str(tests_dir)],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )
    return proc.returncode, proc.stdout, proc.stderr


class TestCheckGeneratedTests(unittest.TestCase):
    def setUp(self) -> None:
        self._temp = tempfile.TemporaryDirectory()
        self.tests_dir = Path(self._temp.name) / "tests"

    def tearDown(self) -> None:
        self._temp.cleanup()

    def test_wellformed_generated_test_passes(self) -> None:
        _write_generated_test(self.tests_dir, "test_law_regress_dod_24.py", REVIEWED_LINE)
        rc, out, err = _run_validator(self.tests_dir)
        self.assertEqual(rc, 0, f"validator red on well-formed test:\n{err}")
        self.assertIn("all generated tests reviewed", out)

    def test_missing_reviewed_by_fires(self) -> None:
        _write_generated_test(self.tests_dir, "test_law_regress_dod_24.py", None)
        rc, _out, err = _run_validator(self.tests_dir)
        self.assertEqual(rc, 1)
        self.assertIn("GENERATED_TEST_UNREVIEWED", err)
        self.assertIn("missing 'reviewed by:'", err)

    def test_empty_reviewed_by_fires(self) -> None:
        _write_generated_test(self.tests_dir, "test_law_regress_dod_24.py", "# reviewed by:")
        rc, _out, err = _run_validator(self.tests_dir)
        self.assertEqual(rc, 1)
        self.assertIn("GENERATED_TEST_UNREVIEWED", err)

    def test_placeholder_reviewed_by_fires(self) -> None:
        _write_generated_test(
            self.tests_dir, "test_law_regress_dod_24.py", "# reviewed by: <user/date>"
        )
        rc, _out, err = _run_validator(self.tests_dir)
        self.assertEqual(rc, 1)
        self.assertIn("placeholder", err)

    def test_missing_auto_marker_fires(self) -> None:
        tests_dir = self.tests_dir
        tests_dir.mkdir(parents=True, exist_ok=True)
        (tests_dir / "test_law_regress_bogus.py").write_text(
            "# reviewed by: Maryam, 2026-10-18\nraise SystemExit(0)\n", encoding="utf-8"
        )
        rc, _out, err = _run_validator(tests_dir)
        self.assertEqual(rc, 1)
        self.assertIn("missing auto-generation header", err)

    def test_non_generated_test_files_ignored(self) -> None:
        _write_generated_test(
            self.tests_dir, "test_something_else.py", None
        )  # hand-written test, no headers at all
        rc, _out, err = _run_validator(self.tests_dir)
        self.assertEqual(rc, 0, f"validator must ignore non-generated files:\n{err}")
        self.assertIn("note: no generated tests", _out)

    def test_empty_tests_dir_passes_with_note(self) -> None:
        self.tests_dir.mkdir(parents=True, exist_ok=True)
        rc, out, err = _run_validator(self.tests_dir)
        self.assertEqual(rc, 0, f"validator red on empty dir:\n{err}")
        self.assertIn("note: no generated tests", out)

    def test_missing_tests_dir_passes_with_note(self) -> None:
        rc, out, err = _run_validator(self.tests_dir)  # dir never created
        self.assertEqual(rc, 0)
        self.assertIn("note: no generated tests", out)


if __name__ == "__main__":
    unittest.main()
